package io.github.hideyukimori.neneclock.domain;

/**
 * 同梱書体の雰囲気（FR-043）。
 *
 * <p>書体を「名前の一覧」ではなく「雰囲気」で選べるようにするための分類であり、
 * 書体の技術的な分類（可変フォントかどうか等）ではない。閉じた選択肢なので列挙で表す（JAV-002）。
 */
public enum TypefaceMood {
    /** 端正で主張が少ない。既定の時計に向く。 */
    SANS,
    /** 落ち着いた明朝・セリフ。 */
    SERIF,
    /** 等幅。桁が動かないので秒の変化で幅が揺れない。 */
    MONO,
    /** 主張の強い見出し書体。 */
    DISPLAY,
    /** 電子機器・SF を思わせる書体。 */
    RETRO,
    /** 手書き。 */
    HAND
}
